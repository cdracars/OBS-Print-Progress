/**
 * Demo G-code generator for the Live Toolpath overlay.
 *
 * Produces a realistic, slicer-style G-code file for a twisted, bulging
 * five-point star tower: purge line, skirt, inner + outer walls, solid
 * bottom/top layers and alternating sparse infill, all tagged with
 * Orca/PrusaSlicer-style `;TYPE:` and `;LAYER_CHANGE` comments.
 *
 * Used by `toolpath.html?demo=1` so the overlay can be tried (and styled in
 * OBS) without a printer, and by the unit tests as a full-size fixture.
 */

(function (root, factory) {
    if (typeof module === 'object' && module.exports) module.exports = factory();
    else root.ToolpathDemo = factory();
})(typeof self !== 'undefined' ? self : this, function () {
    'use strict';

    const FILAMENT_AREA = Math.PI * Math.pow(1.75 / 2, 2);

    function generateDemoGcode(options = {}) {
        const layerHeight = options.layerHeight || 0.25;
        const height = options.height || 48;
        const width = 0.45;
        const cx = options.centerX || 110;
        const cy = options.centerY || 110;
        const points = options.points || 150;
        const bottomLayers = 3;
        const topLayers = 4;
        const layerCount = Math.round(height / layerHeight);

        const out = [];
        const fmt = v => (Math.round(v * 1000) / 1000).toString();
        const ePer = mm => (mm * width * layerHeight) / FILAMENT_AREA;
        let x = 0, y = 0;

        const travel = (nx, ny) => {
            out.push('G1 E-0.8 F2400');
            out.push(`G0 X${fmt(nx)} Y${fmt(ny)} F12000`);
            out.push('G1 E0.8 F2400');
            x = nx; y = ny;
        };
        const extrude = (nx, ny, feed) => {
            const d = Math.hypot(nx - x, ny - y);
            out.push(`G1 X${fmt(nx)} Y${fmt(ny)} E${ePer(d).toFixed(5)}${feed ? ` F${feed}` : ''}`);
            x = nx; y = ny;
        };

        // Radial profile: five lobes, twisting and bulging with height.
        const radius = (theta, z) => {
            const t = z / height;
            const base = 15 + 6 * Math.sin(t * Math.PI) - 3 * t;
            const twist = t * Math.PI * 0.9;
            return base * (1 + 0.2 * Math.cos(5 * theta + twist));
        };
        const outline = (z, inset) => {
            const poly = [];
            for (let k = 0; k < points; k++) {
                const th = (k / points) * Math.PI * 2;
                const r = radius(th, z) - inset;
                poly.push([cx + Math.cos(th) * r, cy + Math.sin(th) * r]);
            }
            return poly;
        };
        const loop = (poly, feed) => {
            travel(poly[0][0], poly[0][1]);
            for (let k = 1; k <= poly.length; k++) {
                const p = poly[k % poly.length];
                extrude(p[0], p[1], k === 1 ? feed : 0);
            }
        };

        out.push('; generated by OBS Print Progress demo mode');
        out.push(`; layer_height = ${layerHeight}`);
        out.push(`; total_layer_count = ${layerCount}`);
        out.push('G90', 'M83', 'G28', 'G1 Z5 F3000');
        out.push(';TYPE:Custom');
        out.push('G0 X5 Y20 Z0.3 F9000');
        x = 5; y = 20;
        extrude(5, 180, 1500);
        extrude(5.5, 180, 0);
        extrude(5.5, 20, 0);

        for (let layer = 0; layer < layerCount; layer++) {
            const z = (layer + 1) * layerHeight;
            out.push(';LAYER_CHANGE', `;Z:${fmt(z)}`, `G1 Z${fmt(z)} F600`);

            if (layer === 0) {
                out.push(';TYPE:Skirt');
                const skirt = [];
                for (let k = 0; k < 120; k++) {
                    const th = (k / 120) * Math.PI * 2;
                    skirt.push([cx + Math.cos(th) * 28, cy + Math.sin(th) * 28]);
                }
                loop(skirt, 1800);
            }

            out.push(';TYPE:Inner wall');
            loop(outline(z, width), layer === 0 ? 1800 : 9000);
            out.push(';TYPE:Outer wall');
            loop(outline(z, 0), layer === 0 ? 1500 : 6000);

            const isBottom = layer < bottomLayers;
            const isTop = layer >= layerCount - topLayers;
            let type, spacing, feed;
            if (isBottom) { type = layer === 0 ? 'Bottom surface' : 'Internal solid infill'; spacing = width; feed = layer === 0 ? 2400 : 9000; }
            else if (isTop) { type = layer === layerCount - 1 ? 'Top surface' : 'Internal solid infill'; spacing = width; feed = layer === layerCount - 1 ? 4800 : 9000; }
            else { type = 'Sparse infill'; spacing = 4.5; feed = 15000; }

            const angle = (layer % 2 ? -1 : 1) * Math.PI / 4;
            const lines = clipLines(outline(z, width * 1.85), angle, spacing);
            if (lines.length) {
                out.push(`;TYPE:${type}`);
                lines.forEach((ln, idx) => {
                    const [a, b] = idx % 2 ? [ln[1], ln[0]] : ln;
                    travel(a[0], a[1]);
                    extrude(b[0], b[1], idx === 0 ? feed : 0);
                });
            }
        }

        out.push(';TYPE:Custom', 'G1 E-2 F2400', 'G91', 'G1 Z10 F600', 'G90', 'M84');
        return out.join('\n') + '\n';
    }

    /**
     * Scanline-clip parallel lines at `angle` against a (possibly concave)
     * polygon. Returns [[x0,y0],[x1,y1]] pairs in scan order.
     */
    function clipLines(poly, angle, spacing) {
        const cos = Math.cos(-angle), sin = Math.sin(-angle);
        const rot = poly.map(([px, py]) => [px * cos - py * sin, px * sin + py * cos]);
        let minY = Infinity, maxY = -Infinity;
        rot.forEach(p => { if (p[1] < minY) minY = p[1]; if (p[1] > maxY) maxY = p[1]; });

        const back = (u, v) => [u * cos + v * sin, -u * sin + v * cos];
        const result = [];
        for (let sy = Math.ceil(minY / spacing) * spacing; sy <= maxY; sy += spacing) {
            const xs = [];
            for (let k = 0; k < rot.length; k++) {
                const a = rot[k], b = rot[(k + 1) % rot.length];
                if ((a[1] <= sy && b[1] > sy) || (b[1] <= sy && a[1] > sy)) {
                    xs.push(a[0] + ((sy - a[1]) / (b[1] - a[1])) * (b[0] - a[0]));
                }
            }
            xs.sort((m, n) => m - n);
            for (let k = 0; k + 1 < xs.length; k += 2) {
                if (xs[k + 1] - xs[k] < 0.5) continue;
                result.push([back(xs[k], sy), back(xs[k + 1], sy)]);
            }
        }
        return result;
    }

    return { generateDemoGcode, clipLines };
});
