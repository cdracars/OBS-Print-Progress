'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../setup.js'), 'utf8');
const start = source.indexOf('    function overlayUrl(');
const end = source.indexOf('    function statusText(', start);
const context = vm.createContext({ URL, location: { origin: 'http://127.0.0.1:8001' } });
vm.runInContext(source.slice(start, end), context);
assert.equal(context.overlayUrl('printer.html', 'sam'), 'http://127.0.0.1:8001/printer.html?printer=sam');
const camera = 'http://192.0.2.91:3031/video';
const safe = new URL(context.overlayUrl('printer.html', 'lucee', camera));
assert.equal(safe.searchParams.get('printer'), 'lucee');
assert.equal(safe.searchParams.get('camera'), camera);
assert.ok(!safe.href.includes('/p/lucee/webcam'));
const twin = new URL(context.overlayUrl('toolpath.html', 'lucee', camera));
assert.equal(twin.searchParams.get('camera'), null);
assert.ok(source.includes("overlayUrl('printer.html', p.id, p.camera)"));
console.log('Watch URLs: unchanged defaults, explicit camera override, and toolpath separation passed.');
